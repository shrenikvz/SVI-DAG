#!/usr/bin/env python
"""
Aggregate the ablation JSONs into the paper's LaTeX table.

    python make_table.py            # -> ablation_table.tex (and stdout)

Reads results/ablation_nonlinear_<variant>.json.  The caption's experimental
settings (p, s, n, iterations) are read from the full-model JSON so the table
can never drift from the runs that produced it.  Missing files or seeds
render as '--' rather than failing, so a partial sweep still produces a table.
"""
from __future__ import annotations

import json
import math
from pathlib import Path

_THIS_DIR = Path(__file__).resolve().parent
RESULTS = _THIS_DIR / "results"
#: Companion exact-recovery study: linear ER p=10 s=10, n=1000, 1500 iters,
#: sampling bias -1 (the small-p setting where the MEC is enumerable and
#: exact posterior hits are a live event).  Regenerate with run_mec_study.py.
MEC_STUDY = RESULTS / "mec_study"
OUT_TEX = _THIS_DIR / "ablation_table.tex"

VARIANT_ROWS = [
    ("full",            r"Full SVI-DAG"),
    ("no_flow",         r"(a) w/o flow"),
    ("no_svgd",         r"(b) w/o SVGD"),
    ("no_prior",        r"(c) w/o domain prior"),
    ("no_flow_no_svgd", r"(d) w/o flow \& SVGD"),
]

# (json key, scale, decimals) per table column, in order.
COLS = [
    ("Brier", 1.0, 3),
    ("E_SHD", 1.0, 1),
    ("E_F1", 100.0, 1),
    ("AUROC", 100.0, 1),
]


def _mean_se(vals):
    n = len(vals)
    if n == 0:
        return None
    mean = sum(vals) / n
    if n == 1:
        return mean, 0.0
    var = sum((v - mean) ** 2 for v in vals) / (n - 1)
    return mean, math.sqrt(var / n)


def _load(variant: str):
    path = RESULTS / f"ablation_nonlinear_{variant}.json"
    if not path.exists():
        return {}
    try:
        return json.loads(path.read_text())
    except (json.JSONDecodeError, OSError):
        return {}


def _mec_cov(variant: str) -> str:
    """mean +- s.e. of MEC coverage (fraction of enumerated true-MEC members
    receiving >=1 exact posterior sample) over the companion study's seeds."""
    path = MEC_STUDY / f"ablation_linear_mec_{variant}.json"
    if not path.exists():
        return "--"
    try:
        rows = json.loads(path.read_text()).get("rows", [])
    except (json.JSONDecodeError, OSError):
        return "--"
    vals = [float(r["mec_cov"]) for r in rows if "mec_cov" in r]
    ms = _mean_se(vals)
    if ms is None:
        return "--"
    mean, se = ms
    return f"{mean:.2f} $\\pm$ {se:.2f}"


def _cell(rows, key, scale, dec):
    vals = [float(r[key]) * scale for r in rows
            if key in r and r[key] == r[key]]      # drop NaN
    ms = _mean_se(vals)
    if ms is None:
        return "--"
    mean, se = ms
    return f"{mean:.{dec}f} $\\pm$ {se:.{dec}f}"


def main() -> int:
    n_seeds = {}
    lines = []
    full_cfg = _load("full")
    for variant, label in VARIANT_ROWS:
        d = _load(variant)
        rows = d.get("rows", [])
        n_seeds[variant] = len(rows)
        cells = [_cell(rows, k, s, dec) for k, s, dec in COLS]
        cells.append(_mec_cov(variant))
        lines.append(f"{label} & " + " & ".join(cells) + r" \\")

    # Caption settings come from the runs themselves.
    p = full_cfg.get("p", "?")
    s = full_cfg.get("s", "?")
    n = full_cfg.get("n_train", "?")
    S = full_cfg.get("posterior_samples", "?")
    it = full_cfg.get("num_iters", "?")
    max_seeds = max(n_seeds.values()) if n_seeds else 0

    seed_note = ", ".join(f"{v}:{k}" for v, k in n_seeds.items())
    tex = "\n".join([
        r"% Auto-generated by paper_results_reproduce/ablation/make_table.py",
        f"% seeds present: {seed_note}",
        r"\begin{table}[t]",
        r"\centering",
        rf"\caption{{Component ablation. Nonlinear ER, $p={p}$, $s={s}$,",
        rf"$n={n}$, $S={S}$ posterior samples, {it} training iterations,",
        rf"mean $\pm$ s.e.\ over {max_seeds} seeds. MEC-cov: expected fraction of",
r"the true Markov equivalence class receiving posterior mass (members",
r"matched exactly by $\geq 1$ of $10^3$ posterior samples), from a",
r"companion study on linear ER graphs ($p=10$, $s=10$, $n=1000$) where the",
r"equivalence class is enumerated exactly.}",
        r"\label{tab:ablation}",
        r"\small",
        r"\begin{tabular}{lccccc}",
        r"\toprule",
        r"Variant & Brier $\downarrow$ & E-SHD $\downarrow$ & "
        r"E-F1 (\%) $\uparrow$ & AUROC (\%) $\uparrow$ & "
        r"MEC-cov $\uparrow$ \\",
        r"\midrule",
        *lines,
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
    ]) + "\n"

    OUT_TEX.write_text(tex)
    print(tex)
    print(f"[make_table] wrote {OUT_TEX}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
